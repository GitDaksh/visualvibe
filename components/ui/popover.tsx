export const PopoverTrigger = PopoverPrimitive.Trigger;
export const PopoverClose = PopoverPrimitive.Close;

export const PopoverContent = React.forwardRef<
  React.ComponentRef<typeof PopoverPrimitive.Content>,
  React.ComponentPropsWithoutRef<typeof PopoverPrimitive.Content>
>(function PopoverContent({ className, align = "start", sideOffset = 8, ...props }, ref) {
  return (
    <PopoverPrimitive.Portal>
      <PopoverPrimitive.Content
        ref={ref}
        align={align}
        sideOffset={sideOffset}
        collisionPadding={12}
        className={cn(
          "z-[55] rounded-[18px] border border-white/10 bg-raised p-3.5 text-paper shadow-[0_24px_60px_rgba(0,0,0,0.6)] outline-none data-[state=open]:animate-pop",
          className,
        )}
        {...props}
      />
    </PopoverPrimitive.Portal>
  );
});
